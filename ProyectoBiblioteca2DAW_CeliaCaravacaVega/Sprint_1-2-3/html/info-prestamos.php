            <h2>Guía de Préstamos – Biblioteca Central</h2>
            <p>En nuestra biblioteca puedes llevarte libros a casa siguiendo estos pasos sencillos:</p>

            <ol>
                <li>
                    <strong>Revisión del catálogo:</strong><br>
                    Busca el libro que deseas en el catálogo físico o digital. Anota el código de estantería o número de
                    referencia.
                </li>

                <li>
                    <strong>Solicita el préstamo:</strong><br>
                    Acércate al mostrador de atención con tu carnet de biblioteca y el libro seleccionado. Entrega ambos
                    al bibliotecario para iniciar el préstamo.
                </li>

                <li>
                    <strong>Registro del préstamo:</strong><br>
                    El personal registrará el libro en el sistema o en el libro de control de préstamos, indicando:
                    <ul>
                        <li>Nombre del usuario</li>
                        <li>Fecha de préstamo</li>
                        <li>Fecha límite de devolución</li>
                    </ul>
                </li>

                <li>
                    <strong>Recibe tu comprobante:</strong><br>
                    Te entregarán un recibo o ticket con la fecha de devolución. Conserva este comprobante hasta
                    devolver el libro.
                </li>

                <li>
                    <strong>Plazo de préstamo:</strong>
                    <ul>
                        <li>Por lo general, los libros se prestan por 15 días hábiles.</li>
                        <li>Algunos libros especiales pueden tener plazos más cortos o solo estar disponibles para
                            consulta dentro de la biblioteca.</li>
                    </ul>
                </li>

                <li>
                    <strong>Renovación:</strong><br>
                    Si no has terminado de leer el libro y no hay reservas pendientes, puedes solicitar una renovación
                    antes de la fecha de entrega para extender el préstamo.
                </li>

                <li>
                    <strong>Devolución:</strong><br>
                    Entrega el libro en el mostrador de la biblioteca antes de la fecha límite. Si devuelves tarde,
                    podrías recibir una multa o restricción temporal en tu cuenta.
                </li>
            </ol>
        </div>

